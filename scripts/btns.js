
function scrollToBreakfast() {
    var element = document.getElementById("h3Breakfast");
    if (element) {
        var rect = element.getBoundingClientRect();
        var offset = window.innerWidth < 600 ? 90 : 150;
        window.scrollTo({
            top: rect.top + window.scrollY - offset,
            behavior: 'smooth'
        });
    }
}

